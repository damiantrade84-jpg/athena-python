def _execution_conviction(signal: dict, engine: str) -> float:
    """Return the engine-specific execution conviction (0-1 scale).

    Engine A rows must be judged on pure Engine A conviction; the scanner
    deflates Engine A score into ``combinedConviction`` (e.g. multiplied by
    ``AUTO_TRADE_A_ONLY_WEIGHT`` when Engine B is absent), so reusing the
    combined value to gate an A-only row would reject otherwise valid Engine A
    signals. Engine C still uses ``combinedConviction`` (the consensus value)
    and Engine B uses its own normalized confidence.
    """
    eng = (engine or "").strip().lower()
    if eng == "engine_c":
        for key in ("combinedConviction", "consensusConviction"):
            raw = signal.get(key)
            if raw is None:
                continue
            try:
                return max(0.0, min(1.0, float(raw)))
            except (TypeError, ValueError):
                continue
        return _current_combined_conviction(signal)
    if eng == "engine_b":
        for key in ("engine_b_conviction", "engine_b_score_norm"):
            raw = signal.get(key)
            if raw is None:
                continue
            try:
                return max(0.0, min(1.0, float(raw)))
            except (TypeError, ValueError):
                continue
        try:
            b_score = float(signal.get("engine_b_score", 0) or 0)
            b_max = float(signal.get("engine_b_max", 0) or 0)
        except (TypeError, ValueError):
            return 0.0
        if b_max > 0:
            return max(0.0, min(b_score / b_max, 1.0))
        return 0.0
    # Engine A or unrecognised engine — fall back to pure Engine A norm.
    for key in ("engine_a_conviction", "scoreNorm", "score_norm"):
        raw = signal.get(key)
        if raw is None:
            continue
        try:
            return max(0.0, min(1.0, float(raw)))
        except (TypeError, ValueError):
            continue
    try:
        score = float(signal.get("confluenceScore", 0) or 0)
    except (TypeError, ValueError):
        return 0.0
    try:
        max_score = float(
            signal.get("maxScoreOverride") or signal.get("maxScore") or 0
        )
    except (TypeError, ValueError):
        max_score = 0.0
    if max_score > 0:
        return max(0.0, min(score / max_score, 1.0))
    if 0.0 <= score <= 1.0:
        return score
    return 0.0


def _current_combined_conviction(signal: dict, cfg: dict | None = None) -> float:
    """Return the execution conviction implied by the signal's current scores."""
    try:
        score = float(signal.get("confluenceScore", 0) or 0)
        max_score = float(signal.get("maxScore", 0) or 0)
    except (TypeError, ValueError):
        return 0.0

    if max_score > 0:
        a_norm = max(0.0, min(score / max_score, 1.0))
    elif 0.0 <= score <= 1.0:
        a_norm = score
    else:
        a_norm = 0.0

    asset_type = str(signal.get("type") or signal.get("assetType") or "").lower()
    a_weight = _engine_a_weight(cfg or {}, asset_type)

    if signal.get("enginesAligned", False):
        try:
            b_score = float(signal.get("engine_b_score", 0) or 0)
            b_max = float(signal.get("engine_b_max", 0) or 0)
        except (TypeError, ValueError):
            b_score = 0.0
            b_max = 0.0
        b_norm = max(0.0, min(b_score / b_max, 1.0)) if b_max > 0 else 0.0
        return round((a_norm * a_weight) + (b_norm * (1.0 - a_weight)), 4)

    return round(a_norm * a_weight, 4)


def _a_only_reject_reason(
    signal: dict,
    combined_conviction: float,
    auto_min_conviction: float,
) -> str | None:
    """Explain the A-only auto gate in Engine A score terms when possible."""
    if signal.get("enginesAligned") is not False:
        return None

    try:
        score = float(signal.get("confluenceScore", 0) or 0)
        max_score = float(signal.get("maxScore", 0) or 0)
    except (TypeError, ValueError):
        return None
    if max_score <= 0 or score < 0:
        return None

    a_norm = score / max_score
    if a_norm <= 0:
        return None
    weight = combined_conviction / a_norm
    if weight <= 0:
        return None

    required_score = (auto_min_conviction / weight) * max_score
    return (
        f"A-only conviction {combined_conviction:.3f} < min {auto_min_conviction:.3f} "
        f"(Engine A score {score:.2f}/{max_score:.1f}; requires about "
        f"{required_score:.2f}/{max_score:.1f} at A-only weight {weight:.2f})"
    )


def _normalize_pair_key(value: str | None) -> str:
    """Normalize pair or symbol identifiers for duplicate-position matching."""
    if value is None:
        return ""
    return "".join(ch for ch in str(value).upper() if ch.isalnum())


def _signal_matches_position(signal: dict, position: dict) -> bool:
    """Return True when a broker position refers to the same instrument."""
    signal_keys = {
        _normalize_pair_key(signal.get("pair")),
        _normalize_pair_key(signal.get("symbol")),
    }
    position_keys = {
        _normalize_pair_key(position.get("pair")),
        _normalize_pair_key(position.get("symbol")),
    }
    signal_keys.discard("")
    position_keys.discard("")
    return bool(signal_keys & position_keys)


