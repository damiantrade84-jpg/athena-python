def _auto_trade_min_conviction_config(cfg: dict) -> dict:
    """Return normalized live auto-trade conviction config."""
    raw = cfg.get("AUTO_TRADE_MIN_CONVICTION", {"default": 0.50})
    if isinstance(raw, dict):
        out = {}
        for key, value in raw.items():
            try:
                out[str(key)] = float(value)
            except (TypeError, ValueError):
                continue
        if not out:
            out["default"] = 0.50
        elif "default" not in out:
            out["default"] = 0.50
        return out
    try:
        return {"default": float(raw)}
    except (TypeError, ValueError):
        return {"default": 0.50}


def _auto_trade_min_conviction(cfg: dict, asset_type: str) -> float:
    conf = _auto_trade_min_conviction_config(cfg)
    return conf.get(asset_type, conf.get("default", 0.50))


def _auto_trade_live_gate_display(cfg: dict) -> str:
    conf = _auto_trade_min_conviction_config(cfg)
    if list(conf.keys()) == ["default"]:
        base = conf["default"]
        return (
            f"executionConvictionEffective >= {base:.2f} "
            f"(aligned >= {base * 0.85:.3f})"
        )

    parts = []
    for key, value in conf.items():
        if key == "default":
            continue
        parts.append(f"{key} {value:.2f}")
    if "default" in conf:
        parts.append(f"default {conf['default']:.2f}")
    return "executionConvictionEffective by asset (" + ", ".join(parts) + "; aligned x0.85)"


def _cfg_bool(cfg: dict, key: str, default: bool = False) -> bool:
    raw = cfg.get(key, default)
    if isinstance(raw, str):
        return raw.strip().lower() in ("1", "true", "yes", "on")
    return bool(raw)


def _clamp01(value, default: float = 0.0) -> float:
    try:
        return max(0.0, min(1.0, float(value)))
    except (TypeError, ValueError):
        return default


def _num(value, default: float | None = None) -> float | None:
    try:
        if value is None:
            return default
        return float(value)
    except (TypeError, ValueError):
        return default


def _first_dict(*values) -> dict:
    for value in values:
        if isinstance(value, dict):
            return value
    return {}


def _json_safe(value):
    try:
        return json.loads(json.dumps(value, default=str))
    except Exception:
        return value


def _tf_seconds(tf: str) -> int:
    return {
        "M1": 60,
        "M5": 300,
        "M15": 900,
        "H1": 3600,
        "H4": 14400,
        "D1": 86400,
    }.get(str(tf or "").upper(), 14400)


def _parse_dt(value) -> datetime | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        dt = value
    elif isinstance(value, (int, float)):
        raw = float(value)
        if raw > 1e12:
            raw = raw / 1000.0
        dt = datetime.fromtimestamp(raw, timezone.utc)
    else:
        try:
            dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        except Exception:
            return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


