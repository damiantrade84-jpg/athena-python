    def _run_auto_scan(self):
        """Run a full scan and auto-execute qualifying signals."""

        if not self._run_scan_fn:
            log.warning("[AUTO] run_scan_fn not configured — skipping")

            return

        if self._kill_switch_fn and self._kill_switch_fn():
            log.info("[AUTO] Kill switch active — scan skipped")

            return

        cfg = self._config_fn() if self._config_fn else {}

        master_block = self._execution_master_block_reason(None, cfg)
        if master_block:
            log.warning("[AUTO] Auto execution blocked before scan: %s", master_block)
            return

        max_daily = cfg.get("AUTO_TRADE_MAX_DAILY", 3)

        with self._lock:
            trades_today = self._trades_today
        if trades_today >= max_daily:
            log.info(
                f"[AUTO] Daily cap reached ({trades_today}/{max_daily}) — scan skipped"
            )

            return

        self._last_scan_at = datetime.now(timezone.utc)

        log.info("[AUTO] Running scan...")

        try:
            result = self._run_scan_fn(style="auto")

        except Exception as e:
            log.error(f"[AUTO] Scan failed: {e}")

            return

        if not result.get("success"):
            log.info(f"[AUTO] Scan returned no success: {result.get('error', '')}")

            return

        signals = result.get("tradeSignals", [])

        watchlist = result.get("watchlist", [])

        funnel = result.get("scanFunnel", {})

        log.info(
            f"[AUTO] Scan done — passed={len(signals)} watchlist={len(watchlist)} "
            f"low_score={funnel.get('low_score', 0)} closed={funnel.get('closed_exchange', 0)} "
            f"inactive={funnel.get('inactive_pair', 0)}"
        )

        if not signals:
            if watchlist:
                top = watchlist[0]

                log.info(
                    f"[AUTO] Best near-miss: {top.get('pair')} score={top.get('confluenceScore')}/{top.get('maxScore')} ({top.get('direction')})"
                )

            return

        # Re-stamp signals generated during this scan cycle to scan-completion time.
        # analyze_pair() timestamps each signal individually; with 90 pairs / 3 workers,
        # the first pairs in the queue can be 3-5 min old by the time the scan returns.
        # Guard: only re-stamp signals within AUTO_TRADE_MAX_SCAN_AGE_SEC of scan start;
        # anything older was not produced in this cycle and must not bypass freshness checks.
        _scan_ts = datetime.now(timezone.utc)
        _scan_ts_iso = _scan_ts.isoformat()
        _max_scan_window = cfg.get("AUTO_TRADE_MAX_SCAN_AGE_SEC", 900)  # 15 min hard cap
        for _s in signals:
            try:
                _sig_age = (_scan_ts - datetime.fromisoformat(
                    _s["timestamp"].replace("Z", "+00:00")
                )).total_seconds()
            except Exception:
                _sig_age = 0
            if _sig_age <= _max_scan_window:
                _s["timestamp"] = _scan_ts_iso
            else:
                log.warning(
                    f"[AUTO] Signal {_s.get('pair')} is {_sig_age:.0f}s old "
                    f"(> {_max_scan_window}s cap) — not re-stamping; will be rejected by risk_check"
                )

        # Rank by executionRankScore. Scanner combinedConviction remains display
        # metadata; ranking no longer recomputes hardcoded A/B weights here.
        for _s in signals:
            _eng = _signal_engine(_s)
            _set_execution_conviction_fields(_s, _eng, cfg)
        signals = sorted(
            signals,
            key=lambda _s: float(_s.get("executionRankScore", 0.0) or 0.0),
            reverse=True,
        )

        max_per_scan = cfg.get("AUTO_TRADE_MAX_PER_SCAN", 1)
        try:
            naked_max_daily = int(cfg.get("NAKED_MAX_DAILY", 0) or 0)
        except (TypeError, ValueError):
            naked_max_daily = 0

        executed = 0
        positions_cache: dict[str, list[dict] | None] = {}

        for candidate_rank, sig in enumerate(signals, start=1):
            _ensure_auto_decision_trace(sig, cfg, candidate_rank=candidate_rank)
            if executed >= max_per_scan:
                break

            with self._lock:
                if self._trades_today >= max_daily:
                    break
                if naked_max_daily > 0 and _signal_engine(sig) == "engine_b":
                    pair_key = _signal_pair_key(sig)
                    if pair_key and self._naked_trades_today_by_pair.get(pair_key, 0) >= naked_max_daily:
                        log.info(
                            f"[AUTO] {sig.get('pair')} skipped: Engine B daily pair cap "
                            f"{naked_max_daily} reached"
                        )
                        _finalize_trace(
                            sig,
                            cfg,
                            action="block",
                            stage="daily_pair_cap",
                            reason=f"NAKED_MAX_DAILY:{naked_max_daily}",
                        )
                        self._write_error(sig, f"NAKED_MAX_DAILY:{naked_max_daily}")
                        continue

            timing_ok, timing_reason = self._refresh_execution_timing(sig, cfg)
            if not timing_ok:
                log.info(f"[AUTO] {sig.get('pair')} skipped: {timing_reason}")
                _finalize_trace(
                    sig,
                    cfg,
                    action="block",
                    stage="executionTimingRefresh",
                    reason=timing_reason,
                )
                self._write_error(sig, timing_reason)
                continue

            ok, reason = self._can_execute(sig, cfg)

            if not ok:
                log.info(f"[AUTO] {sig.get('pair')} skipped: {reason}")
                _finalize_trace(
                    sig,
                    cfg,
                    action="block",
                    stage=sig.get("autoDecisionTrace", {}).get("failedStage") or "can_execute",
                    reason=reason,
                )
                self._write_error(sig, reason)

                continue

            open_positions = self._get_cached_open_positions(
                sig.get("type", ""), positions_cache
            )
            if open_positions is not None:
                # Block same-pair duplicates
                if any(_signal_matches_position(sig, pos) for pos in open_positions):
                    log.info(
                        f"[AUTO] {sig.get('pair')} skipped: already holding open position"
                    )
                    signal_precheck = {
                        "checked": True,
                        "allowed": False,
                        "reason": "already_holding_open_position",
                    }
                    sig["brokerPrecheck"] = signal_precheck
                    _finalize_trace(
                        sig,
                        cfg,
                        action="block",
                        stage="brokerPrecheck",
                        reason="ALREADY_HOLDING_OPEN_POSITION",
                    )
                    self._write_error(sig, "ALREADY_HOLDING_OPEN_POSITION")
                    continue

                # Block when venue is already at max positions — avoids wasting the full
                # execution path (AI debate, sentiment, risk_check) on a guaranteed rejection
                _max_open = int(cfg.get("MAX_OPEN_POSITIONS", 5))
                if len(open_positions) >= _max_open:
                    log.info(
                        f"[AUTO] {sig.get('pair')} skipped: {len(open_positions)} open "
                        f"positions >= MAX_OPEN_POSITIONS {_max_open}"
                    )
                    sig["brokerPrecheck"] = {
                        "checked": True,
                        "allowed": False,
                        "reason": "max_open_positions",
                        "openPositions": len(open_positions),
                        "maxOpenPositions": _max_open,
                    }
                    _finalize_trace(
                        sig,
                        cfg,
                        action="block",
                        stage="brokerPrecheck",
                        reason=f"MAX_OPEN_POSITIONS:{len(open_positions)}/{_max_open}",
                    )
                    self._write_error(sig, f"MAX_OPEN_POSITIONS:{len(open_positions)}/{_max_open}")
                    continue
                sig["brokerPrecheck"] = {
                    "checked": True,
                    "allowed": True,
                    "openPositions": len(open_positions),
                    "maxOpenPositions": int(cfg.get("MAX_OPEN_POSITIONS", 5)),
                }

            success = self._execute_signal(sig, cfg)

            if success:
                executed += 1
                if naked_max_daily > 0 and _signal_engine(sig) == "engine_b":
                    pair_key = _signal_pair_key(sig)
                    if pair_key:
                        with self._lock:
                            self._naked_trades_today_by_pair[pair_key] = (
                                self._naked_trades_today_by_pair.get(pair_key, 0) + 1
                            )

        log.info(f"[AUTO] Scan complete — {executed} trade(s) executed")

    def _hydrate_conductor_routing(self, signal: dict) -> None:
        """Attach deterministic conductor routing to signal when audit DB is configured."""
        _audit = getattr(self, "_audit_db", None) or ""
        if not _audit:
            return
        ex = signal.get("conductor")
        if isinstance(ex, dict) and "skip_signal" in ex and "run_debate" in ex:
            return
        try:
            from conductor import conductor_orchestrate, extract_conductor_microstructure

            context = extract_auto_trade_context(signal)
            _vd, _sr = extract_conductor_microstructure(signal)
            micro = context.get("microstructureContext") if isinstance(context, dict) else {}
            if isinstance(micro, dict) and micro:
                if _sr is None and micro.get("liquidityWallDetection"):
                    _sr = {
                        "stop_run": True,
                        "source": "engine_a_microstructure",
                        "detail": micro.get("liquidityWallDetection"),
                    }
                if _vd is None and micro.get("volumeMomentumSpread") is not None:
                    _vd = {
                        "divergence": bool(micro.get("volumeMomentumSpread")),
                        "source": "engine_a_microstructure",
                        "value": micro.get("volumeMomentumSpread"),
                    }
            news_risk = self._news_risk_text(context)
            plan = conductor_orchestrate(
                signal,
                signal.get("regime", "UNKNOWN"),
                _audit,
                news_ctx=context.get("newsSentimentSummary"),
                volume_divergence=_vd,
                stop_run=_sr,
                news_risk=news_risk,
            )
            signal["conductor"] = plan.get("routing", {})
            signal["conductor_context"] = plan.get("context", {})
            if isinstance(signal["conductor"], dict):
                signal["conductor"].setdefault("advisoryOnly", True)
                signal["conductor"].setdefault("notUsedForExecution", True)
        except Exception as _e:
            log.warning("[AUTO] conductor hydrate failed: %s", _e)

    def _refresh_execution_timing(
        self,
        signal: dict,
        cfg: dict,
    ) -> tuple[bool, str]:
        """Refresh authoritative Engine B timing before execution gates."""
        from timeframe_policy import policy_mode_is_authoritative

        if (
            _signal_engine(signal) != "engine_b"
            or not policy_mode_is_authoritative(None, cfg)
            or not (
                signal.get("timeframePolicyVersion")
                or signal.get("executionTf")
                or signal.get("execution_tf_policy")
            )
        ):
            return True, "OK"
        try:
            from athena_runtime import rt as _auto_rt
            from execution import _refresh_engine_b_execution_context

            engine_b_context = signal.get("engine_b") or signal.get("naked_data") or {}
            refreshed, error = _refresh_engine_b_execution_context(
                signal,
                engine_b_context,
                _auto_rt(),
                str(signal.get("style") or "intraday"),
            )
        except Exception as exc:
            return False, f"ENGINE_B_REFRESH_FAILED: {exc}"
        if error or not refreshed:
            return False, error or "ENGINE_B_REFRESH_FAILED: no refreshed context"
        return True, "OK"

    def _can_execute(self, signal: dict, cfg: dict) -> tuple[bool, str]:
        """Check deterministic auto-execution gates without mutating Engine A score."""

        from timeframe_policy import timeframe_policy_execution_block_reason

        timeframe_policy_block = timeframe_policy_execution_block_reason(signal, cfg)
        if timeframe_policy_block:
            return False, timeframe_policy_block

        if (
            str(signal.get("engine") or "").upper() == "ENGINE_A_V3"
            and str(signal.get("contractVersion") or "").startswith("3.")
        ):
            return False, "ENGINE_A_V3_MANUAL_DEMO_ONLY"

        asset_type = signal.get("type", "")
        engine_name = _signal_engine(signal)
        context = extract_auto_trade_context(signal)
        _set_execution_conviction_fields(signal, engine_name, cfg)
        _ensure_auto_decision_trace(signal, cfg)

        master_block = self._execution_master_block_reason(signal, cfg)
        if master_block:
            signal["masterExecutionGate"] = {"allowed": False, "reason": master_block}
            _trace_gate(signal, cfg, "masterExecution", signal["masterExecutionGate"])
            _finalize_trace(signal, cfg, action="block", stage="masterExecution", reason=master_block)
            return False, master_block
        signal["masterExecutionGate"] = {"allowed": True}
        _trace_gate(signal, cfg, "masterExecution", signal["masterExecutionGate"])

        if _signal_engine(signal) not in ("engine_b", "scalp"):
            from engine_a_trade_gate import engine_a_trade_gate_block_reason

            _ea_block = engine_a_trade_gate_block_reason(signal, config=cfg)
            if _ea_block:
                signal["engineATradeGateBlock"] = {"allowed": False, "reason": _ea_block}
                _trace_gate(signal, cfg, "engineATradeGate", signal["engineATradeGateBlock"])
                _finalize_trace(signal, cfg, action="block", stage="engineATradeGate", reason=_ea_block)
                return False, _ea_block

        engines_aligned = signal.get("enginesAligned", False)
        effective_conviction = _clamp01(signal.get("executionConvictionEffective"))
        auto_min_conviction = _auto_trade_min_conviction(cfg, asset_type)
        aligned_discount_applied = False
        if engines_aligned:
            auto_min_conviction = auto_min_conviction * 0.85
            aligned_discount_applied = True
        signal["alignedDiscountApplied"] = aligned_discount_applied

        calibration = predict_calibrated_prob(
            effective_conviction,
            engine=engine_name,
            asset_class=asset_type,
            style=signal.get("style"),
            max_score=1.0,
            db_path=self._audit_db,
        )
        signal["calibratedProbability"] = calibration.get("calibrated_prob")
        signal["calibration"] = calibration
        from timeframe_policy import policy_mode_is_authoritative

        # F5 remains unresolved.  A promoted forward-demo policy result must
        # not be routed through the meta-labeler path, which can otherwise
        # alter its execution threshold using potentially leaky historical
        # state.  Deterministic execution/risk gates below remain active.
        if policy_mode_is_authoritative(None, cfg):
            meta = {}
            signal["metaLabelerApplied"] = False
            signal["metaLabelerReason"] = "F5_INTEGRITY_ISOLATION"
            signal["metaThresholdDelta"] = 0.0
            signal["metaSuspended"] = False
            signal["metaEngineWeight"] = 0.0
        else:
            meta = meta_report(signal, db_path=self._audit_db) if self._audit_db else meta_report(signal, records=[])
            signal.update(apply_meta_policy(signal, meta))
            signal["metaLabelerApplied"] = True
        meta_delta = float(signal.get("metaThresholdDelta", 0.0) or 0.0)
        auto_min_conviction = max(0.0, min(1.0, auto_min_conviction + meta_delta))
        signal["autoMinConviction"] = round(auto_min_conviction, 6)
        _trace_update(
            signal,
            cfg,
            executionConvictionBase=signal.get("executionConvictionBase"),
            executionConvictionEffective=signal.get("executionConvictionEffective"),
            executionConvictionSource=signal.get("executionConvictionSource"),
            executionRankScore=signal.get("executionRankScore"),
            minConviction=signal.get("autoMinConviction"),
            alignedDiscountApplied=aligned_discount_applied,
            calibration=calibration,
            metaPolicy={
                "metaEngineWeight": signal.get("metaEngineWeight"),
                "metaThresholdDelta": signal.get("metaThresholdDelta"),
                "metaSuspended": signal.get("metaSuspended"),
            },
        )

        b_score = signal.get("engine_b_score", 0)
        b_max = signal.get("engine_b_max", 5)
        b_verdict = signal.get("engine_b_verdict", "N/A")
        log.info(
            f"[AUTO] {signal.get('pair')} candidate: execConviction={effective_conviction:.3f} min={auto_min_conviction:.3f} "
            f"source={signal.get('executionConvictionSource')} rank={signal.get('executionRankScore')} "
            f"cal={calibration.get('calibrated_prob')} scope={calibration.get('scope_used')} "
            f"fallback={calibration.get('fallback_reason')} "
            f"meta_w={signal.get('metaEngineWeight')} meta_d={signal.get('metaThresholdDelta')} "
            f"meta_suspend={signal.get('metaSuspended')} "
            f"aligned={engines_aligned} A={signal.get('confluenceScore', 0):.2f}/{signal.get('maxScore', 3)} "
            f"B={b_score}/{b_max} ({b_verdict}) dir={signal.get('direction')}"
        )

        if signal.get("metaSuspended"):
            _finalize_trace(signal, cfg, action="block", stage="metaPolicy", reason="META_POLICY_SUSPENDED")
            return False, "meta policy suspended this engine bucket"

        if effective_conviction < auto_min_conviction:
            a_only_reason = _a_only_reject_reason(
                signal,
                float(effective_conviction),
                float(auto_min_conviction),
            )
            reason = a_only_reason or f"conviction {effective_conviction:.3f} < min {auto_min_conviction:.3f}"
            _finalize_trace(signal, cfg, action="block", stage="conviction", reason=reason)
            return False, reason

        # Regime filter — only execute in TRENDING regime (37% WR vs 11% RANGING, 0% DEVELOPING)
        _trend_state = signal.get("trendState", "UNKNOWN")
        _regime = signal.get(
            "regimeName",
            signal.get("regime", {}).get("label", "UNKNOWN")
            if isinstance(signal.get("regime"), dict)
            else "UNKNOWN",
        )
        _blocked_state_cfg = cfg.get("AUTO_TRADE_BLOCKED_TREND_STATES", {})
        if isinstance(_blocked_state_cfg, dict):
            _blocked_states = set(
                _blocked_state_cfg.get(
                    asset_type, _blocked_state_cfg.get("default", ["DEAD RANGING", "RANGING"])
                )
            )
        else:
            _blocked_states = set(_blocked_state_cfg or ["DEAD RANGING", "RANGING"])

        _blocked_regime_cfg = cfg.get("AUTO_TRADE_BLOCKED_REGIMES", {})
        if isinstance(_blocked_regime_cfg, dict):
            _blocked_regimes = {
                str(v).upper()
                for v in _blocked_regime_cfg.get(
                    asset_type, _blocked_regime_cfg.get("default", ["RANGING"])
                )
            }
        else:
            _blocked_regimes = {str(v).upper() for v in (_blocked_regime_cfg or ["RANGING"])}

        # NOTE: Engine A v2 now routes forex through the shared factor engine as well.
        # trendState is still not a reliable forex regime label, so this blocked-state
        # filter has little practical effect on forex. If forex-specific regime blocking
        # is needed, filter on signal.get("regimeName") instead.
        if _trend_state in _blocked_states or _regime.upper() in _blocked_regimes:
            reason = f"Regime filter: {_trend_state}/{_regime} blocked for auto-trade"
            _finalize_trace(signal, cfg, action="block", stage="regime", reason=reason)
            return (
                False,
                reason,
            )

        now = datetime.now(timezone.utc)

        # ── Market hours guard — block execution when market is closed ──────
        utc_weekday = now.weekday()  # 0=Mon, 6=Sun
        utc_total = now.hour * 60 + now.minute

        if asset_type in ("forex", "index", "commodity"):
            # Forex/forex-adjacent: closed Fri 22:00 UTC → Sun 22:00 UTC
            forex_closed = (
                utc_weekday == 5  # all Saturday
                or (utc_weekday == 6 and utc_total < 22 * 60)  # Sunday before 22:00
                or (utc_weekday == 4 and utc_total >= 22 * 60)  # Friday after 22:00
            )
            if forex_closed:
                reason = f"MARKET_CLOSED: {asset_type} market is closed (weekend)"
                _finalize_trace(signal, cfg, action="block", stage="marketHours", reason=reason)
                return False, reason

        if asset_type in ("stock", "index"):
            # Equity markets: only Mon-Fri
            if utc_weekday >= 5:
                reason = f"MARKET_CLOSED: {asset_type} market is closed (weekend)"
                _finalize_trace(signal, cfg, action="block", stage="marketHours", reason=reason)
                return False, reason
            # JSE/LSE/DAX: 07:00–15:30 UTC | NYSE: 13:30–20:00 UTC
            # Use a broad window Mon-Fri 07:00–21:00 UTC to cover all equity sessions
            if not (7 * 60 <= utc_total < 21 * 60):
                reason = f"MARKET_CLOSED: {asset_type} market hours are 07:00-21:00 UTC"
                _finalize_trace(signal, cfg, action="block", stage="marketHours", reason=reason)
                return False, reason

        # crypto is always open — no guard needed

        session_cfg = cfg.get("AUTO_TRADE_SESSIONS", {})

        allowed_sessions = session_cfg.get(asset_type, ["always"])

        if "always" not in allowed_sessions:
            current_sessions = _current_sessions(now)

            if not any(s in current_sessions for s in allowed_sessions):
                reason = f"outside trading session ({current_sessions})"
                _finalize_trace(signal, cfg, action="block", stage="session", reason=reason)
                return False, reason

        slot_ok, slot_reason, slot_detail = _confirmed_close_execution_allowed(signal, cfg, now)
        slot_key = _auto_trade_slot_key(
            signal,
            slot_detail.get("timeframe"),
            slot_detail.get("lastConfirmedCandleTs"),
        )
        slot_detail["slotKey"] = list(slot_key)
        with self._lock:
            already_executed = slot_key in self._executed_slots
        if already_executed:
            slot_ok = False
            slot_reason = "CONFIRMED_CLOSE_SLOT_ALREADY_EXECUTED"
            slot_detail.update({"allowed": False, "reason": "slot_already_executed"})
        _trace_gate(signal, cfg, "confirmedClose", slot_detail)
        if not slot_ok:
            _finalize_trace(signal, cfg, action="block", stage="confirmedClose", reason=slot_reason)
            return False, slot_reason

        sl_ok, sl_reason, sl_detail = self._sl_distance_precheck(signal, asset_type, cfg)
        _trace_gate(signal, cfg, "slDistance", sl_detail)
        if not sl_ok:
            _finalize_trace(signal, cfg, action="block", stage="slDistance", reason=sl_reason)
            return False, sl_reason

        major_risk = context.get("majorEventRisk") if isinstance(context, dict) else {}
        if isinstance(major_risk, dict) and major_risk.get("blocksAutoExecution"):
            signal["eventRiskGate"] = {
                "checked": False,
                "source": "majorEventRisk",
                "result": major_risk,
            }
            reason = major_risk.get("reason") or "MAJOR_EVENT_RISK_BLOCK"
            _finalize_trace(signal, cfg, action="block", stage="majorEventRisk", reason=reason)
            return False, reason

        im_ok, im_reason = self._intermarket_execution_gate(signal, cfg, context)
        _trace_update(signal, cfg, intermarketExecutionGate=signal.get("intermarketExecutionGate"))
        if not im_ok:
            _finalize_trace(signal, cfg, action="block", stage="intermarket", reason=im_reason)
            return False, im_reason

        micro_ok, micro_reason = self._microstructure_execution_gate(signal, cfg, context)
        _trace_update(
            signal,
            cfg,
            microstructureGate=signal.get("microstructureGate"),
            executionConvictionEffective=signal.get("executionConvictionEffective"),
        )
        if not micro_ok:
            _finalize_trace(signal, cfg, action="block", stage="microstructure", reason=micro_reason)
            return False, micro_reason

        self._hydrate_conductor_routing(signal)
        _routing_pre = signal.get("conductor") if isinstance(signal.get("conductor"), dict) else {}
        _trace_update(signal, cfg, conductorRouting=_routing_pre)
        if _routing_pre.get("skip_signal"):
            _rsn = _routing_pre.get("reasons", [])
            reason = f"CONDUCTOR_SKIP: {'; '.join(str(x) for x in _rsn)}"
            _finalize_trace(signal, cfg, action="block", stage="conductor", reason=reason)
            return False, reason

        sent_ok, sent_reason = self._sentiment_gate_allowed(signal, cfg, context, _routing_pre, asset_type)
        _trace_update(signal, cfg, sentimentGate=signal.get("sentimentGate"))
        if not sent_ok:
            _finalize_trace(signal, cfg, action="block", stage="sentiment", reason=sent_reason)
            return False, sent_reason

        if cfg.get("EVENT_RISK_ENABLED", True):
            try:
                from event_risk import check_event_risk

                ev_risk = check_event_risk(
                    signal.get("pair", ""),
                    asset_type,
                    lookahead_hours=cfg.get("EVENT_RISK_HOURS", 4),
                )
                signal["eventRiskGate"] = ev_risk
                _trace_update(signal, cfg, eventRiskGate=ev_risk)

                if not ev_risk.get("allowed", False):
                    reason = ev_risk.get("reason", "Event risk block")
                    _finalize_trace(signal, cfg, action="block", stage="eventRisk", reason=reason)
                    return False, reason

            except ImportError:
                reason = "Event risk gate unavailable"
                _finalize_trace(signal, cfg, action="block", stage="eventRisk", reason=reason)
                return False, reason
        else:
            signal["eventRiskGate"] = {
                "allowed": True,
                "reason": "EVENT_RISK_ENABLED=false",
                "eventRiskStatus": {"enabled": False, "effectiveAction": "skipped_disabled"},
            }
            _trace_update(signal, cfg, eventRiskGate=signal["eventRiskGate"])

        # Signal debate gate — AI Bull/Bear/Judge evaluation before auto-execution
        if cfg.get("SIGNAL_DEBATE_ENABLED", True):
            try:
                from ai_reconciliation import arbitrate_ai
                from signal_debate import run_signal_debate

                _co = signal.get("conductor")
                routing = _co if isinstance(_co, dict) else {}

                if isinstance(routing, dict) and routing.get("run_debate") is False:
                    debate = {
                        "grade": "SKIP",
                        "reasoning": "conductor: run_debate false — debate not routed",
                        "allowed": True,
                        "trace_id": signal.get("trace_id"),
                    }
                else:
                    debate = run_signal_debate(signal)
                _grade = debate.get("grade", "SKIP")
                _ai_decision = arbitrate_ai(
                    {"debate": debate, "trace_id": debate.get("trace_id") or signal.get("trace_id")},
                    require_trace_id=True,
                    required_sources=("debate",),
                )
                signal["ai_arbitration"] = _ai_decision
                _allowed = bool(_ai_decision.get("execution_allowed"))
                _reasoning = debate.get("reasoning", "")
                log.info(f"[AUTO] {signal.get('pair')} debate: {_grade} — {_reasoning}")
                signal["aiDebateGate"] = {
                    "checked": True,
                    "grade": _grade,
                    "allowed": _allowed,
                    "arbitration": _ai_decision,
                    "reasoning": _reasoning,
                    "scoreMutationEnabled": False,
                }
                # AI debate Telegram notification disabled
                if not _allowed:
                    reason = f"AI arbitration: {_ai_decision.get('reason')} (debate={_grade})"
                    _trace_update(signal, cfg, aiDebateGate=signal["aiDebateGate"])
                    _finalize_trace(signal, cfg, action="block", stage="aiDebate", reason="AI_ARBITRATION_BLOCK")
                    return False, reason
                # Debate may only reduce execution conviction. Engine A score fields
                # remain server/scoring-owned and are never mutated here.
                _adj_eff = float(
                    debate.get("score_penalty", debate.get("score_adjustment", 0.0)) or 0.0
                )
                if _adj_eff > 0:
                    log.critical(
                        "[AUTO] %s debate returned positive adjustment %.4f — forcing 0 (CRIT-002)",
                        signal.get("pair"),
                        _adj_eff,
                    )
                    _adj_eff = 0.0
                _adj_raw = float(
                    debate.get("score_adjustment_raw")
                    if debate.get("score_adjustment_raw") is not None
                    else _adj_eff
                )
                _adj = _adj_eff
                _debate_adjustment_clamped = _adj_raw > 0.0 and _adj == 0.0
                if _adj != 0.0:
                    max_score = _num(signal.get("maxScore"), 1.0) or 1.0
                    penalty = abs(_adj) / max_score if max_score > 1.0 else abs(_adj)
                    penalty = _clamp01(penalty)
                    before_ai = _clamp01(signal.get("executionConvictionEffective"))
                    after_ai = max(0.0, before_ai - penalty)
                    signal["aiDebatePenalty"] = round(penalty, 6)
                    signal["executionConvictionAfterAi"] = round(after_ai, 6)
                    signal["executionConvictionEffective"] = round(after_ai, 6)
                    signal["aiDebateGate"].update(
                        {
                            "scoreAdjustmentRaw": _adj_raw,
                            "scoreAdjustmentAppliedToScore": 0.0,
                            "executionConvictionBefore": round(before_ai, 6),
                            "executionConvictionPenalty": round(penalty, 6),
                            "executionConvictionAfter": round(after_ai, 6),
                        }
                    )
                    if signal["executionConvictionEffective"] < auto_min_conviction:
                        _trace_update(
                            signal,
                            cfg,
                            aiDebateGate=signal["aiDebateGate"],
                            executionConvictionEffective=signal.get("executionConvictionEffective"),
                        )
                        reason = (
                            f"debate-adjusted execution conviction {signal['executionConvictionEffective']:.3f} "
                            f"< min {auto_min_conviction:.3f}"
                        )
                        _finalize_trace(signal, cfg, action="block", stage="aiDebate", reason=reason)
                        return (
                            False,
                            reason,
                        )
                if _debate_adjustment_clamped:
                    log.debug(
                        "[AUTO] %s debate score_adjustment=%.3f clamped to 0.0 (downgrade-only policy)",
                        signal.get("pair"), _adj_raw,
                    )
                signal["_debate_adjustment_clamped"] = _debate_adjustment_clamped
                signal["aiDebateGate"]["positiveAdjustmentClamped"] = _debate_adjustment_clamped
                _trace_update(
                    signal,
                    cfg,
                    aiDebateGate=signal["aiDebateGate"],
                    executionConvictionEffective=signal.get("executionConvictionEffective"),
                )

                try:
                    from ai_review_logger import (
                        extract_engine_d_audit_state,
                        log_ai_review,
                        map_debate_grade_to_ai_state,
                        REVIEW_TYPE_SIGNAL_DEBATE,
                    )
                    from prompt_versions import get_prompt_version

                    log_ai_review(
                        symbol=signal.get("pair", "?"),
                        asset_type=asset_type,
                        review_type=REVIEW_TYPE_SIGNAL_DEBATE,
                        model=cfg.get("DEBATE_MODEL", "unknown"),
                        provider="xAI",
                        prompt_version=get_prompt_version("debate_judge"),
                        input_packet={
                            "pair": signal.get("pair"),
                            "trace_id": debate.get("trace_id") or signal.get("trace_id"),
                            "grade": _grade,
                            "reasoning": (debate.get("reasoning") or "")[:500],
                            "bull_conviction": debate.get("bull_conviction"),
                            "bear_conviction": debate.get("bear_conviction"),
                            "score": signal.get("confluenceScore"),
                            "score_adjustment": debate.get("score_adjustment"),
                            "execution_conviction_effective": signal.get("executionConvictionEffective"),
                            "arbitration": _ai_decision,
                        },
                        has_chart_image=False,
                        candle_freshness_status=(
                            (signal.get("dataFreshness") or {}).get("reason") or "unknown"
                        ),
                        engine_a_state=signal.get("confluenceScore"),
                        engine_b_state=None,
                        engine_c_state=signal.get("executionConvictionEffective"),
                        engine_d_state=extract_engine_d_audit_state(signal),
                        risk_state=None,
                        ai_review_state=map_debate_grade_to_ai_state(_grade),
                        ai_confidence=None,
                        contradictions_count=0,
                        missing_information_count=0,
                        parse_success=True,
                        schema_valid=True,
                        execution_allowed_before_ai=True,
                        execution_allowed_after_ai=_allowed,
                        final_action="debate_gate",
                        trace_id=debate.get("trace_id") or signal.get("trace_id"),
                    )
                except Exception as _log_err:
                    log.debug("[AI_AUDIT] Debate audit log failed: %s", _log_err)

            except ImportError:
                log.debug("[AUTO] signal_debate not available — skipping")
                reason = "AI debate unavailable"
                _finalize_trace(signal, cfg, action="block", stage="aiDebate", reason=reason)
                return False, reason
            except Exception as _debate_err:
                log.warning(f"[AUTO] Debate failed (blocking): {_debate_err}")
                reason = f"AI debate failed: {_debate_err}"
                _finalize_trace(signal, cfg, action="block", stage="aiDebate", reason=reason)
                return False, reason
        else:
            signal["aiDebateGate"] = {"checked": False, "skippedReason": "disabled"}
            _trace_update(signal, cfg, aiDebateGate=signal["aiDebateGate"])

        chart_ok, chart_reason = self._chart_ai_gate_allowed(signal, cfg)
        _trace_update(signal, cfg, aiChartGate=signal.get("aiChartGate"))
        if not chart_ok:
            _finalize_trace(signal, cfg, action="block", stage="aiChart", reason=chart_reason)
            return False, chart_reason

        _finalize_trace(signal, cfg, action="allow", stage="", reason="")
        return True, ""

    def _get_cached_open_positions(
        self, asset_type: str, positions_cache: dict[str, list[dict] | None]
    ) -> list[dict] | None:
        """Load broker open positions once per venue during a scan.

        Returns an empty list when positions cannot be confirmed (logs warning).
        Execution fails closed downstream in risk_check, so this precheck only
        suppresses known duplicate-pair attempts — a miss here is not a safety gap.
        """
        venue = "bybit" if asset_type == "crypto" else "mt5"
        if venue in positions_cache:
            return positions_cache[venue]

        try:
            if venue == "bybit":
                from bybit_executor import bybit_get_positions

                pos_result = bybit_get_positions()
            else:
                from mt5_executor import mt5_get_positions

                pos_result = mt5_get_positions()
        except Exception as e:
            log.warning(f"[AUTO] {venue.upper()} positions precheck failed: {e}")
            positions_cache[venue] = []
            return []

        if isinstance(pos_result, dict) and pos_result.get("error"):
            log.warning(
                f"[AUTO] {venue.upper()} positions precheck unavailable: "
                f"{pos_result.get('detail', 'unknown')}"
            )
            positions_cache[venue] = []
            return []

        positions = (
            pos_result.get("positions", [])
            if isinstance(pos_result, dict)
            else (pos_result or [])
        )
        positions_cache[venue] = positions
        return positions

    def _execute_signal(self, signal: dict, cfg: dict) -> bool:
        """Execute a single signal through the normal risk → executor path.

        On any failure, writes a tagged error row to audit_log for diagnosis.

        """

        pair = signal.get("pair", "")

        direction = signal.get("direction", "")

        is_crypto = signal.get("type") == "crypto"
        ssi_engine = _signal_engine(signal)
        _ensure_auto_decision_trace(signal, cfg)

        master_block = self._execution_master_block_reason(signal, cfg)
        if master_block:
            _finalize_trace(signal, cfg, action="block", stage="masterExecution", reason=master_block)
            self._write_error(signal, master_block)
            return False

        try:
            from risk_engine import risk_check

            if is_crypto:
                from bybit_executor import (
                    bybit_get_account,
                    bybit_get_positions,
                    bybit_get_symbol_info,
                )

                account = bybit_get_account()

                if not account:
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "account", "reason": "BYBIT_NOT_CONNECTED"}
                    self._write_error(signal, "BYBIT_NOT_CONNECTED")

                    return False

                pos_result = bybit_get_positions()
                if isinstance(pos_result, dict) and pos_result.get("error"):
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "positions", "reason": "BYBIT_POSITIONS_UNAVAILABLE"}
                    self._write_error(signal, "BYBIT_POSITIONS_UNAVAILABLE")
                    return False
                positions = (
                    pos_result.get("positions", [])
                    if isinstance(pos_result, dict)
                    else (pos_result or [])
                )

                symbol_info = bybit_get_symbol_info(pair)

                if not symbol_info or symbol_info.get("error"):
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "symbol", "reason": "BYBIT_SYMBOL_UNAVAILABLE"}
                    self._write_error(signal, "BYBIT_SYMBOL_UNAVAILABLE")

                    return False

                _exec_venue = "bybit"
                signal["brokerPrecheck"] = {"allowed": True, "venue": _exec_venue}

            else:
                from mt5_executor import (
                    mt5_get_account,
                    mt5_get_positions,
                    mt5_get_symbol_info,
                )

                account = mt5_get_account()

                if not account or account.get("error"):
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "account", "reason": "MT5_NOT_CONNECTED"}
                    self._write_error(signal, "MT5_NOT_CONNECTED")

                    return False

                pos_result = mt5_get_positions()
                if isinstance(pos_result, dict) and pos_result.get("error"):
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "positions", "reason": "MT5_POSITIONS_UNAVAILABLE"}
                    self._write_error(signal, "MT5_POSITIONS_UNAVAILABLE")
                    return False
                positions = (
                    pos_result.get("positions", [])
                    if isinstance(pos_result, dict)
                    else (pos_result or [])
                )

                symbol_info = mt5_get_symbol_info(pair)

                if not symbol_info:
                    signal["brokerPrecheck"] = {"allowed": False, "stage": "symbol", "reason": f"SYMBOL_NOT_ON_BROKER:{pair}"}
                    self._write_error(signal, f"SYMBOL_NOT_ON_BROKER:{pair}")

                    return False

                _exec_venue = "mt5"
                signal["brokerPrecheck"] = {"allowed": True, "venue": _exec_venue}

            # The account object comes from the live broker connection.  This
            # is the final policy account-scope gate and must run immediately
            # before any risk or executor call; a scan-level test/demo flag is
            # not a substitute for broker metadata.
            from timeframe_policy import timeframe_policy_execution_block_reason

            policy_account_block = timeframe_policy_execution_block_reason(
                signal, cfg, account
            )
            policy_execution = signal.get("timeframePolicyExecution")
            if isinstance(policy_execution, dict):
                log.info(
                    "[AUTO][TF_POLICY] accountId=%s broker=%s accountEnvironment=%s "
                    "policyMode=%s executionAllowed=%s executionRestrictionReason=%s",
                    policy_execution.get("accountId"),
                    policy_execution.get("broker"),
                    policy_execution.get("accountEnvironment"),
                    policy_execution.get("policyMode"),
                    policy_execution.get("executionAllowed"),
                    policy_execution.get("executionRestrictionReason"),
                )
            if policy_account_block:
                signal["brokerPrecheck"] = {
                    "allowed": False,
                    "stage": "timeframe_policy_account",
                    "venue": _exec_venue,
                    "reason": policy_account_block,
                }
                self._write_error(signal, policy_account_block)
                return False

            from execution_lifecycle import run_managed_execution

            # F1: parity with api_execute / api_quick_execute. Refresh candle
            # freshness/consistency/dataFreshness before risk_check so stale scan
            # metadata cannot reach the risk gate. Default-on via
            # EXECUTION_HYDRATE_CANDLE_QUALITY; falls back to the lighter
            # _maybe_prefetch_execution_candle_fetch_meta path on any error.
            try:
                from execution import _hydrate_execution_candle_quality
                from athena_runtime import rt as _auto_rt

                _hydrate_execution_candle_quality(signal, _r=_auto_rt())
                signal["candleHydration"] = {"attempted": True, "status": "ok"}
            except Exception as _hydrate_err:
                log.warning(
                    "[AUTO] %s: candle quality hydrate skipped (%s)",
                    pair,
                    _hydrate_err,
                )
                signal["candleHydration"] = {
                    "attempted": True,
                    "status": "error",
                    "reason": str(_hydrate_err),
                }

            sizing_override = cfg.get("AUTO_TRADE_SIZING_OVERRIDE", 1.0)

            # Engine A exit-mode selector (Plan 2): resolve mode + advisable-pip
            # clamp before risk_check so auto-traded Engine A signals honor the
            # selected mode (audit H1). No-op for non-Engine-A signals.
            from exit_mode_apply import (
                apply_engine_a_exit_mode,
                apply_engine_b_exit_strategy,
            )
            apply_engine_a_exit_mode(
                signal, _signal_engine(signal), symbol_info, cfg, None
            )
            # Engine B exit-strategy/runner-directive stamp (no level mutation);
            # no-op for non-Engine-B signals.
            apply_engine_b_exit_strategy(signal, _signal_engine(signal), cfg)

            # F2: parity with the manual paths (api_execute /
            # api_quick_execute). Route the auto path through the same
            # pre-risk broker-price refresh (+ Engine B RR reconcile after
            # rebase) and the shared displacement guard, with identical
            # block-reason vocabulary. Fail-closed: any block aborts before
            # risk_check and is audit-logged like the other pre-risk gates.
            from execution import (
                _displacement_guard_block_reason,
                _engine_b_pre_risk_broker_price,
                _reconcile_engine_b_rr_after_broker_entry,
            )

            _drift_error, _drift_diag = _engine_b_pre_risk_broker_price(
                signal, _exec_venue, cfg
            )
            if _drift_error:
                log.warning(f"[AUTO] {pair} BROKER PRE-RISK BLOCKED: {_drift_error}")
                signal["brokerPrecheck"] = {
                    "allowed": False,
                    "stage": "pre_risk_broker_price",
                    "venue": _exec_venue,
                    "reason": _drift_error,
                }
                _finalize_trace(
                    signal, cfg, action="block", stage="preRiskBrokerPrice", reason=_drift_error
                )
                self._write_error(signal, _drift_error)
                return False
            if _drift_diag:
                signal["brokerDriftPreRisk"] = _drift_diag

            _rr_reconcile_error = _reconcile_engine_b_rr_after_broker_entry(signal, cfg)
            if _rr_reconcile_error:
                log.warning(f"[AUTO] {pair} RR RECONCILE BLOCKED: {_rr_reconcile_error}")
                _finalize_trace(
                    signal, cfg, action="block", stage="rrReconcile", reason=_rr_reconcile_error
                )
                self._write_error(signal, _rr_reconcile_error)
                return False

            _chase_error, _chase_diag = _displacement_guard_block_reason(signal, cfg)
            signal["displacementGuard"] = _chase_diag
            if _chase_error:
                log.warning(f"[AUTO] {pair} DISPLACEMENT GUARD BLOCKED: {_chase_error}")
                _finalize_trace(
                    signal, cfg, action="block", stage="displacementGuard", reason=_chase_error
                )
                self._write_error(signal, _chase_error)
                return False

            approval = risk_check(
                signal=signal,
                account_balance=account["balance"],
                account_equity=account["equity"],
                open_positions=positions,
                symbol_info=symbol_info,
                kill_switch=self._kill_switch_fn() if self._kill_switch_fn else False,
                sizing_override=sizing_override,
                execution_context="auto",
                account_domain=account.get("risk_domain"),
            )

            if not approval.approved:
                signal["riskApproval"] = {
                    "approved": False,
                    "reason": approval.reason,
                    "riskAmount": getattr(approval, "risk_amount", None),
                    "riskPct": getattr(approval, "risk_pct", None),
                }
                self._write_error(signal, f"RISK:{approval.reason}")

                return False
            signal["riskApproval"] = {
                "approved": True,
                "reason": approval.reason,
                "riskAmount": getattr(approval, "risk_amount", None),
                "riskPct": getattr(approval, "risk_pct", None),
                "volume": getattr(approval, "volume", None),
            }

            from guardian import pre_trade_check as _guardian_pre_trade
            _ptc_ok, _ptc_reason = _guardian_pre_trade(signal, positions, account, pos_result)
            signal["guardianDecision"] = {
                "allowed": bool(_ptc_ok),
                "reason": _ptc_reason,
            }
            if not _ptc_ok:
                log.warning(f"[AUTO] {pair} GUARDIAN BLOCKED: {_ptc_reason}")
                self._write_error(signal, f"GUARDIAN:{_ptc_reason}")
                return False

            result = run_managed_execution(_exec_venue, signal, approval)
            signal["executionResult"] = result

            if result.get("success"):
                with self._lock:
                    self._trades_today += 1
                    self._last_exec_at = datetime.now(timezone.utc)
                    self._last_exec_pair = pair
                    self._last_exec_dir = direction

                self._mark_executed_slot(signal, cfg)
                _finalize_trace(signal, cfg, action="execute", stage="execution", reason="")
                self._write_audit(signal, approval, result, cfg)
                record_execution_event(
                    engine=ssi_engine,
                    success=True,
                    score=signal.get("confluenceScore"),
                    max_score=signal.get("maxScore", 1.0),
                    expected_prob=_signal_expected_prob(signal),
                    slippage_bps=result.get("slippageBps"),
                    db_path=self._audit_db,
                    meta={
                        "pair": pair,
                        "direction": direction,
                        "calibrated_probability": signal.get("calibratedProbability"),
                        "runtime_only_metric": True,
                    },
                )

                # Send Telegram notification for successful auto-execution
                try:
                    import telegram_notify
                    
                    # Get AI analysis if available
                    ai_analysis = signal.get("ai_analysis", {})
                    factor_diagnostics = signal.get("factorDiagnostics") or {}
                    scoring_timeframes = (
                        factor_diagnostics.get("scoringTimeframes") or {}
                        if isinstance(factor_diagnostics, dict)
                        else {}
                    )
                    telegram_notify.notify_signal_with_ai(
                        pair=signal.get("pair", ""),
                        direction=signal.get("direction", ""),
                        score=signal.get("confluenceScore", 0),
                        max_score=signal.get("maxScore", 3.0),
                        entry=signal.get("price", 0),
                        sl=signal.get("sl", 0),
                        tp1=signal.get("tp1", 0),
                        rr1=signal.get("rr1", 0),
                        regime=signal.get("trendState", ""),
                        signal_class=signal.get("signalClass", ""),
                        ai_grade=ai_analysis.get("grade", ""),
                        ai_verdict=ai_analysis.get("verdict", ""),
                        ai_edge_prob=ai_analysis.get("edgeProbability", 0),
                        ai_risk=ai_analysis.get("riskLevel", ""),
                        ai_warnings=ai_analysis.get("warnings", []),
                        is_auto_executed=True,
                        momentum_tf=scoring_timeframes.get("momentum"),
                        trigger_tf=scoring_timeframes.get("trigger") or signal.get("triggerTf"),
                    )
                except Exception as tn_e:
                    log.debug(f"[AUTO] Telegram notification failed: {tn_e}")

                log.warning(
                    f"[AUTO] EXECUTED: {pair} {direction} "
                    f"ticket={result.get('ticket')} vol={result.get('volume')}"
                )

                return True

            else:
                err = result.get("error", "UNKNOWN")

                _finalize_trace(signal, cfg, action="block", stage="execution", reason=f"EXEC:{err}")
                self._write_error(signal, f"EXEC:{err}")

                return False

        except Exception as e:
            _finalize_trace(signal, cfg, action="block", stage="exception", reason=f"EXCEPTION:{str(e)[:120]}")
            self._write_error(signal, f"EXCEPTION:{str(e)[:120]}")

            log.error(f"[AUTO] _execute_signal error for {pair}: {e}")

            return False

    def _write_audit(self, signal: dict, approval, result: dict, cfg: dict):
        """Write auto-trade to audit_log."""

        if not self._audit_db:
            return

        is_demo = self._test_mode_fn() if self._test_mode_fn else False

        def _infer_asset_class(pair: str) -> str | None:
            """Infer asset class from pair name when signal['type'] is missing."""
            if not pair:
                return None
            p = pair.upper()
            if "/USDT" in p or "/BTC" in p or "/ETH" in p:
                return "crypto"
            if any(p.startswith(fx) for fx in (
                "EUR/", "GBP/", "USD/", "AUD/", "NZD/", "CAD/", "CHF/", "JPY/",
                "EUR", "GBP", "AUD", "NZD", "CAD", "CHF"
            )) and "/" in p:
                return "forex"
            if p in ("XAU/USD", "XAG/USD", "OIL", "BRENT", "SUGAR", "WHEAT",
                     "CORN", "COFFEE", "COTTON", "NATURAL GAS", "COCOA"):
                return "commodity"
            if any(x in p for x in ("SPX", "NDX", "DAX", "FTSE", "NQ", "ES",
                                      "SP500", "US30", "UK100", "GER40")):
                return "index"
            return "stock"

        def _resolve_audit_style(style: str | None, asset_class: str | None) -> str:
            """Normalise style for audit_log. Maps 'auto' and None to a concrete style."""
            if style in ("scalp", "intraday", "swing"):
                return style
            # 'auto' or None — infer from asset class
            if (asset_class or "").lower() == "crypto":
                return "intraday"   # crypto auto defaults to intraday
            if (asset_class or "").lower() == "forex":
                return "intraday"
            return "intraday"       # safe default for commodity/index/stock

        def _audit_legs() -> list[dict]:
            raw_legs = result.get("legs") if isinstance(result.get("legs"), list) else []
            if not raw_legs:
                return [
                    {
                        "ticket": result.get("ticket"),
                        "entryPrice": result.get("entryPrice") or signal.get("price"),
                        "tp": signal.get("tp1"),
                        "volume": result.get("volume"),
                        "riskAmount": approval.risk_amount,
                        "riskPct": approval.risk_pct,
                    }
                ]
            total_volume = sum(float(leg.get("volume") or 0.0) for leg in raw_legs)
            legs = []
            for leg in raw_legs:
                leg_volume = float(leg.get("volume") or 0.0)
                ratio = (leg_volume / total_volume) if total_volume > 0 else 0.0
                legs.append(
                    {
                        "ticket": leg.get("ticket"),
                        "entryPrice": leg.get("entryPrice") or result.get("entryPrice") or signal.get("price"),
                        "tp": leg.get("tp") or signal.get("tp1"),
                        "volume": leg_volume,
                        "riskAmount": approval.risk_amount * ratio,
                        "riskPct": approval.risk_pct * ratio,
                    }
                )
            return legs

        try:
            _audit_engine = _signal_engine(signal)
            _eng_b_data = signal.get("engine_b") or signal.get("naked_data") or {}
            _factors = {
                "scores": _signal_factor_scores(signal),
                "weights": _signal_factor_weights(signal),
                "disabled": signal.get("disabledFactors"),
                "regime": signal.get("regimeName"),
                "combined_conviction": signal.get("combinedConviction"),
                "executionConvictionBase": signal.get("executionConvictionBase"),
                "executionConvictionEffective": signal.get("executionConvictionEffective"),
                "executionRankScore": signal.get("executionRankScore"),
                "calibrated_probability": signal.get("calibratedProbability"),
                "scoreAttribution": _score_attribution(signal),
                "nonVisualContext": _non_visual_context(signal),
                "newsSentimentSummary": signal.get("newsSentimentSummary"),
                "majorEventRisk": signal.get("majorEventRisk"),
                "intermarketConfirmation": signal.get("intermarketConfirmation"),
                "conductorRouting": signal.get("conductor"),
                "conductorContext": signal.get("conductor_context"),
                "aiArbitration": signal.get("ai_arbitration"),
                "autoDecisionTrace": signal.get("autoDecisionTrace"),
            }
            _max_score = (
                _eng_b_data.get("max_possible")
                if _audit_engine == "engine_b"
                else signal.get("maxScore")
            )
            _score_pct = (
                _eng_b_data.get("pct")
                if _audit_engine == "engine_b"
                else (
                    signal.get("confluenceScore") / _max_score
                    if _max_score and _max_score > 0
                    else None
                )
            )
            with timed_sqlite_connect(
                self._audit_db, timeout=15.0, label="auto.audit_success.connect"
            ) as con:
                for _leg in _audit_legs():
                    timed_sqlite_execute_write(
                        con,
                        "INSERT INTO audit_log"
                        "(ts, pair, score, engine, direction, asset_class, regime,"
                        " entry_price, sl, tp, volume, risk_amount, risk_pct,"
                        " ticket, grade, signal_price_ref, slippage_bps,"
                        " max_score, score_pct, factors_json, edge_prob, style, fee_cost, exit_mode)"
                        " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                        (
                            datetime.now(timezone.utc).isoformat(),
                            signal.get("pair"),
                            signal.get("confluenceScore"),
                            _audit_engine,
                            signal.get("direction"),
                            signal.get("type") or _infer_asset_class(signal.get("pair", "")),
                            signal.get("trendState"),
                            _leg.get("entryPrice"),
                            signal.get("sl"),
                            _leg.get("tp"),
                            _leg.get("volume"),
                            _leg.get("riskAmount"),
                            _leg.get("riskPct"),
                            _leg.get("ticket"),
                            "AUTO" + ("-DEMO" if is_demo else ""),
                            result.get("signalPriceRef"),
                            result.get("slippageBps"),
                            _max_score,
                            _score_pct,
                            json.dumps(_json_safe(_factors)),
                            signal.get("calibratedProbability", signal.get("edgeProbability")),
                            _resolve_audit_style(signal.get("style"), signal.get("type")),
                            result.get("feeCost"),
                            signal.get("exit_mode"),
                        ),
                        label="auto.audit_success.insert",
                    )

                timed_sqlite_commit(con, label="auto.audit_success.commit")

        except Exception as e:
            log.debug(f"[AUTO] audit write failed: {e}")

    def _write_error(self, signal: dict, error_tag: str):
        """Write a failed auto-trade attempt to audit_log with an error_tag for diagnosis."""

        if not self._audit_db:
            return

        is_demo = self._test_mode_fn() if self._test_mode_fn else False

        log.warning(f"[AUTO] {signal.get('pair')} FAILED — {error_tag}")
        cfg = self._config_fn() if self._config_fn else {}
        if not isinstance(cfg, dict):
            cfg = {}
        trace = _ensure_auto_decision_trace(signal, cfg)
        if not trace.get("finalAction"):
            _finalize_trace(
                signal,
                cfg,
                action="block",
                stage=trace.get("failedStage") or "unknown",
                reason=error_tag,
            )
        _factors = {
            "scores": _signal_factor_scores(signal),
            "weights": _signal_factor_weights(signal),
            "combined_conviction": signal.get("combinedConviction"),
            "executionConvictionBase": signal.get("executionConvictionBase"),
            "executionConvictionEffective": signal.get("executionConvictionEffective"),
            "executionRankScore": signal.get("executionRankScore"),
            "scoreAttribution": _score_attribution(signal),
            "nonVisualContext": _non_visual_context(signal),
            "newsSentimentSummary": signal.get("newsSentimentSummary"),
            "majorEventRisk": signal.get("majorEventRisk"),
            "intermarketConfirmation": signal.get("intermarketConfirmation"),
            "conductorRouting": signal.get("conductor"),
            "aiArbitration": signal.get("ai_arbitration"),
            "riskReason": (
                _first_dict(signal.get("riskApproval")).get("reason")
                if isinstance(signal.get("riskApproval"), dict)
                else None
            ),
            "guardianReason": (
                _first_dict(signal.get("guardianDecision")).get("reason")
                if isinstance(signal.get("guardianDecision"), dict)
                else None
            ),
            "autoDecisionTrace": signal.get("autoDecisionTrace"),
        }

        try:
            record_execution_event(
                engine=_signal_engine(signal),
                success=False,
                score=signal.get("confluenceScore"),
                max_score=signal.get("maxScore", 1.0),
                expected_prob=_signal_expected_prob(signal),
                db_path=self._audit_db,
                meta={
                    "pair": signal.get("pair"),
                    "direction": signal.get("direction"),
                    "error": error_tag,
                    "calibrated_probability": signal.get("calibratedProbability"),
                    "runtime_only_metric": True,
                },
            )
        except Exception as _ssi_err:
            log.debug(f"[SSI] auto-trader failure sample skipped: {_ssi_err}")

        try:
            with timed_sqlite_connect(
                self._audit_db, timeout=15.0, label="auto.audit_error.connect"
            ) as con:
                timed_sqlite_execute_write(
                    con,
                    """INSERT INTO audit_log

                       (ts, pair, score, engine, direction, asset_class, regime,

                        entry_price, sl, tp, grade, error_tag, factors_json)

                       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                    (
                        datetime.now(timezone.utc).isoformat(),
                        signal.get("pair"),
                        signal.get("confluenceScore"),
                        _signal_engine(signal),
                        signal.get("direction"),
                        signal.get("type"),
                        signal.get("trendState"),
                        signal.get("price"),
                        signal.get("sl"),
                        signal.get("tp1"),
                        "AUTO-ERR" + ("-DEMO" if is_demo else ""),
                        error_tag,
                        json.dumps(_json_safe(_factors)),
                    ),
                    label="auto.audit_error.insert",
                )

                timed_sqlite_commit(con, label="auto.audit_error.commit")

        except Exception as e:
            log.debug(f"[AUTO] error audit write failed: {e}")


