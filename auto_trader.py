def _engine_a_weight(cfg: dict, asset_type: str) -> float:
    raw = cfg.get("AUTO_TRADE_A_ONLY_WEIGHT", {"default": 0.60})
    value = None
    if isinstance(raw, dict):
        value = raw.get(asset_type, raw.get("default", 0.60))
